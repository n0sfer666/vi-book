mod common;

use common::{check, t};

#[test]
fn charwise_motions() {
    check(&[
        t("l moves right", "abc", (0, 0), "l", "abc", (0, 1)),
        t("l stops at line end", "abc", (0, 2), "l", "abc", (0, 2)),
        t("h moves left", "abc", (0, 2), "h", "abc", (0, 1)),
        t("h stops at col 0", "abc", (0, 0), "h", "abc", (0, 0)),
        t(
            "3l moves three right",
            "abcdef",
            (0, 0),
            "3l",
            "abcdef",
            (0, 3),
        ),
        t(
            "10l clamps at line end",
            "abc",
            (0, 0),
            "10l",
            "abc",
            (0, 2),
        ),
        t(
            "0 moves to line start",
            "hello",
            (0, 3),
            "0",
            "hello",
            (0, 0),
        ),
        t(
            "dollar moves to line end",
            "hello",
            (0, 1),
            "$",
            "hello",
            (0, 4),
        ),
        t(
            "dollar on empty line stays",
            "\nabc",
            (0, 0),
            "$",
            "\nabc",
            (0, 0),
        ),
        t(
            "l over multibyte char counts chars",
            "héllo",
            (0, 0),
            "ll",
            "héllo",
            (0, 2),
        ),
    ]);
}

#[test]
fn linewise_motions() {
    check(&[
        t("j moves down", "abc\ndef", (0, 1), "j", "abc\ndef", (1, 1)),
        t(
            "j stops at last line",
            "abc\ndef",
            (1, 0),
            "j",
            "abc\ndef",
            (1, 0),
        ),
        t("k moves up", "abc\ndef", (1, 1), "k", "abc\ndef", (0, 1)),
        t(
            "k stops at first line",
            "abc\ndef",
            (0, 1),
            "k",
            "abc\ndef",
            (0, 1),
        ),
        t(
            "2j moves two down",
            "a\nb\nc",
            (0, 0),
            "2j",
            "a\nb\nc",
            (2, 0),
        ),
        t(
            "j clamps to shorter line",
            "abcdef\nab",
            (0, 4),
            "j",
            "abcdef\nab",
            (1, 1),
        ),
        t(
            "jj remembers desired column",
            "abcdef\nab\nabcdef",
            (0, 4),
            "jj",
            "abcdef\nab\nabcdef",
            (2, 4),
        ),
        t(
            "horizontal move resets desired column",
            "abcdef\nab\nabcdef",
            (0, 4),
            "jhk",
            "abcdef\nab\nabcdef",
            (0, 0),
        ),
        t(
            "dollar then j sticks to line end",
            "abc\nabcdef",
            (0, 0),
            "$j",
            "abc\nabcdef",
            (1, 5),
        ),
        t(
            "dollar stickiness persists over short line",
            "abcdef\nab\nabcdef",
            (0, 0),
            "$jj",
            "abcdef\nab\nabcdef",
            (2, 5),
        ),
    ]);
}

#[test]
fn word_motions() {
    check(&[
        t(
            "w to next word",
            "hello world",
            (0, 0),
            "w",
            "hello world",
            (0, 6),
        ),
        t(
            "w stops at punctuation",
            "foo.bar",
            (0, 0),
            "w",
            "foo.bar",
            (0, 3),
        ),
        t(
            "w from punctuation to word",
            "foo.bar",
            (0, 3),
            "w",
            "foo.bar",
            (0, 4),
        ),
        t(
            "w crosses line",
            "foo\nbar",
            (0, 0),
            "w",
            "foo\nbar",
            (1, 0),
        ),
        t(
            "w lands on empty line",
            "foo\n\nbar",
            (0, 0),
            "w",
            "foo\n\nbar",
            (1, 0),
        ),
        t(
            "w at last word goes to last char",
            "hello world",
            (0, 6),
            "w",
            "hello world",
            (0, 10),
        ),
        t(
            "w skips multiple spaces",
            "a   b",
            (0, 0),
            "w",
            "a   b",
            (0, 4),
        ),
        t(
            "3w jumps three words",
            "one two three four",
            (0, 0),
            "3w",
            "one two three four",
            (0, 14),
        ),
        t(
            "w with cyrillic words",
            "привет мир",
            (0, 0),
            "w",
            "привет мир",
            (0, 7),
        ),
        t(
            "b to previous word start",
            "hello world",
            (0, 6),
            "b",
            "hello world",
            (0, 0),
        ),
        t(
            "b from middle of word to its start",
            "hello world",
            (0, 8),
            "b",
            "hello world",
            (0, 6),
        ),
        t("b across line", "foo\nbar", (1, 0), "b", "foo\nbar", (0, 0)),
        t(
            "b stops at punctuation",
            "foo.bar",
            (0, 4),
            "b",
            "foo.bar",
            (0, 3),
        ),
        t(
            "2b jumps two words back",
            "one two three",
            (0, 8),
            "2b",
            "one two three",
            (0, 0),
        ),
        t("b at buffer start stays", "abc", (0, 0), "b", "abc", (0, 0)),
        t(
            "e to word end",
            "hello world",
            (0, 0),
            "e",
            "hello world",
            (0, 4),
        ),
        t(
            "e at word end jumps to next word end",
            "hello world",
            (0, 4),
            "e",
            "hello world",
            (0, 10),
        ),
        t(
            "e stops before punctuation",
            "foo.bar",
            (0, 0),
            "e",
            "foo.bar",
            (0, 2),
        ),
        t(
            "2e jumps two word ends",
            "one two three",
            (0, 0),
            "2e",
            "one two three",
            (0, 6),
        ),
        t(
            "e crosses line",
            "foo\nbar",
            (0, 2),
            "e",
            "foo\nbar",
            (1, 2),
        ),
    ]);
}

#[test]
fn buffer_motions() {
    check(&[
        t("G to last line", "a\nb\nc", (0, 0), "G", "a\nb\nc", (2, 0)),
        t(
            "gg to first line",
            "a\nb\nc",
            (2, 0),
            "gg",
            "a\nb\nc",
            (0, 0),
        ),
        t(
            "G lands on first non-blank",
            "a\n  b",
            (0, 0),
            "G",
            "a\n  b",
            (1, 2),
        ),
        t(
            "gg lands on first non-blank",
            "  a\nb",
            (1, 0),
            "gg",
            "  a\nb",
            (0, 2),
        ),
        t(
            "3G goes to line 3",
            "a\nb\nc\nd",
            (0, 0),
            "3G",
            "a\nb\nc\nd",
            (2, 0),
        ),
        t(
            "2gg goes to line 2",
            "a\nb\nc",
            (2, 0),
            "2gg",
            "a\nb\nc",
            (1, 0),
        ),
        t(
            "100G clamps to last line",
            "a\nb",
            (0, 0),
            "100G",
            "a\nb",
            (1, 0),
        ),
        t(
            "G with trailing newline lands on last real line",
            "a\nb\n",
            (0, 0),
            "G",
            "a\nb\n",
            (1, 0),
        ),
        t(
            "esc cancels pending count",
            "abcdef",
            (0, 0),
            "3<Esc>l",
            "abcdef",
            (0, 1),
        ),
    ]);
}
