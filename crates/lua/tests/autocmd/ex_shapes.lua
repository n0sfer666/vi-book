local api=vibook
local group=api.create_augroup('ExShapes',{})
api.cmd('augroup ExShapes\nau User foo set number\nau User fo* set readonly\nau! User fo*\naugroup END')
local rows=api.get_autocmds({group=group})
assert(#rows == 1 and rows[1].pattern == 'foo')
api.cmd('au! ExShapes User Once,Once set number')
rows=api.get_autocmds({group=group,pattern='Once'})
assert(#rows == 1)
assert(not pcall(api.cmd,'au ExShapes User Duplicate ++once ++once set number'))
assert(#api.get_autocmds({group=group,pattern='Duplicate'}) == 0)
api.cmd('au ExShapes User UnknownFlag ++unknown set number')
assert(api.get_autocmds({group=group,pattern='UnknownFlag'})[1].command == '++unknown set number')
api.cmd('augroup ExShapes')
assert(not pcall(api.del_augroup_by_id,group))
api.create_autocmd('User',{pattern='DefaultFromAPI',command='set number'})
api.cmd('au!\naugroup END')
assert(#api.get_autocmds({group=group}) == 0)
assert(#api.get_autocmds({event='User',pattern='DefaultFromAPI'}) == 1)
api.cmd('au! User DefaultFromAPI')
api.cmd('au ExShapes User Retired set number\naugroup! ExShapes')
assert(not pcall(api.get_autocmds,{group=group}))
local retired=api.get_autocmds({event='User',pattern='Retired'})
assert(#retired == 1 and retired[1].group_name == '--Deleted--')
api.o.number=false
api.cmd('do <nomodeline> User Retired')
assert(api.o.number)
