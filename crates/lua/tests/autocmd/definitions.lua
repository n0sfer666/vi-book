local group = vibook.create_augroup('NativeContract', {})
local callback = function() return false end
local id = vibook.create_autocmd({'User', 'BufRead'}, {
  group = group, pattern = {'one,two', '*.md'}, callback = callback,
  once = true, nested = true, desc = '',
})
local rows = vibook.get_autocmds({id = id})
assert(#rows == 6)
assert(rows[1].event == 'BufReadPost' and rows[4].event == 'User')
assert(rows[1].pattern == 'one' and rows[2].pattern == 'two')
assert(rows[1].callback == callback and rows[1].command == '')
assert(rows[1].group == group and rows[1].group_name == 'NativeContract')
assert(rows[1].once and rows[1].nested == nil and rows[1].desc == '')
assert(not rows[1].buflocal and rows[1].buffer == nil)
assert(#vibook.get_autocmds({id=id, event={}}) == 0)
assert(#vibook.get_autocmds({id=id, pattern={}}) == 6)
assert(#vibook.get_autocmds({id=id, pattern='one,two'}) == 0)
assert(#vibook.get_autocmds({id=id, pattern={'one','two'}}) == 4)
assert(#vibook.get_autocmds({id=0, event='User'}) == 0)
assert(#vibook.get_autocmds({id=-1, group=group}) == 6)
vibook.clear_autocmds({event='User'})
assert(#vibook.get_autocmds({id=id}) == 6)
vibook.clear_autocmds({event='User', group='NativeContract', pattern='one'})
assert(#vibook.get_autocmds({id=id}) == 5)
assert(vibook.create_augroup('NativeContract', {clear=false}) == group)
assert(#vibook.get_autocmds({id=id}) == 5)
assert(vibook.create_augroup('NativeContract', {}) == group)
assert(#vibook.get_autocmds({id=id}) == 0)
local empty = vibook.create_autocmd('User', {command=''})
local row = vibook.get_autocmds({id=empty})[1]
assert(row.command == '' and row.callback == nil and row.pattern == '*')
vibook.del_autocmd(empty)
assert(#vibook.get_autocmds({id=empty}) == 0)
local named = vibook.create_autocmd('User', {callback='NoSuchFunction'})
assert(vibook.get_autocmds({id=named})[1].callback == '<vim function: NoSuchFunction>')
vibook.clear_autocmds({})
assert(#vibook.get_autocmds({id=named}) == 0)
vibook.del_augroup_by_id(group)
assert(not pcall(vibook.del_augroup_by_id, group))
local other = vibook.create_augroup('RemoveByName', {})
vibook.create_autocmd('User', {group=other, command=''})
vibook.del_augroup_by_name('RemoveByName')
assert(not pcall(vibook.get_autocmds, {group='RemoveByName'}))
assert(not pcall(vibook.create_autocmd, 'User,BufEnter', {command=''}))
assert(not pcall(vibook.create_autocmd, 'User', {}))
assert(not pcall(vibook.create_autocmd, 'User', {command='', callback=callback}))
assert(not pcall(vibook.create_autocmd, 'User', {group=0, command=''}))
assert(not pcall(vibook.create_autocmd, 'User', {buffer=0, pattern='*', command=''}))
assert(not pcall(vibook.create_autocmd, 'User', {nonsense=true, command=''}))
assert(not pcall(vibook.get_autocmds, {nonsense=true}))
assert(not pcall(vibook.clear_autocmds, {id=1}))
